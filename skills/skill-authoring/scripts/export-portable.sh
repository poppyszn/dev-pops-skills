#!/usr/bin/env bash
# Flatten a skill's SKILL.md + references into one portable, plain-text
# instructions document for agents that have no Skill tool (no on-demand
# skill loading) — e.g. a static instructionsBundle pasted in at agent
# setup. See skill-authoring's references/standard.md §13.
#
# Usage:
#   export-portable.sh <skill-dir> [<skill-dir>...]  # print one doc per skill to stdout
#   export-portable.sh --all                         # every skill next to this one
#   export-portable.sh --check <file>                # exit non-zero if <file> no longer
#                                                      # matches a fresh export of the skill
#                                                      # named in its header (staleness check)
set -euo pipefail

skills_root="$(cd -P "$(dirname "$0")/../.." && pwd)"

# Same tiny frontmatter reader as validate.sh, duplicated on purpose so this
# script has no dependency on another script's internals.
fm_value() {
  sed -nE "s/^$2:[[:space:]]*(.*[^[:space:]])[[:space:]]*$/\1/p" <<<"$1" | head -n 1 \
    | sed -E 's/^"(.*)"$/\1/; s/^'\''(.*)'\''$/\1/'
}

# Phrases that only make sense inside a Skill-tool runtime (on-demand
# loading, slash-command invocation, artifact rendering). None of the
# skills in this repo should contain them (standard §9 already forbids
# naming agent products), but flag rather than silently drop, so an author
# notices and rewords the source instead of trusting the export to fix it.
flag_terms='skill tool|slash command|\B/loop\b|claude artifact'

render() {
  local dir="${1%/}" skill file frontmatter name desc version verified body ref
  skill="$(basename "$dir")"
  file="$dir/SKILL.md"
  [[ -f "$file" ]] || { echo "no SKILL.md in $dir" >&2; return 1; }

  frontmatter="$(awk 'NR==1{next} /^---$/{exit} {print}' "$file")"
  name="$(fm_value "$frontmatter" name)"
  desc="$(fm_value "$frontmatter" description)"
  version="$(fm_value "$frontmatter" '[[:space:]]+version')"
  verified="$(fm_value "$frontmatter" '[[:space:]]+last-verified')"
  body="$(awk 'BEGIN{n=0} /^---$/{n++; next} n>=2{print}' "$file")"

  cat <<EOF
<!-- dev-pops-skills portable export: skill=$skill version=$version last-verified=$verified
     Generated by scripts/export-portable.sh from skills/$skill/SKILL.md.
     Do not hand-edit this file: regenerate it instead, or edits will be lost
     and it will silently drift from the source skill.
     This document is a flat, static copy for an agent with no on-demand
     skill loading. Read all of it before acting; nothing here is lazy. -->

# $skill

$desc

$body
EOF

  for ref in "$dir"/references/*.md; do
    [[ -e "$ref" ]] || continue
    [[ "$(basename "$ref")" == sources.md ]] && continue
    printf '\n---\n\n## Appendix: references/%s\n\n' "$(basename "$ref")"
    cat "$ref"
  done

  if [[ -d "$dir/assets" ]] && [[ -n "$(find "$dir/assets" -type f -print -quit)" ]]; then
    printf '\n---\n\n## Assets\n\n'
    echo "Template files this skill tells you to copy are not inlined above."
    echo "They live in this repo's checkout under \`skills/$skill/assets/\`. Copy"
    echo "them with a file-copy command (e.g. \`cp\`); never retype them from"
    echo "this document — retyping drops fixes baked into the template."
    echo
    find "$dir/assets" -type f | sed "s#^$dir/#- \`#; s#\$#\`#"
  fi
}

check_terms() {
  local text="$1" hits
  if hits="$(grep -niE "$flag_terms" <<<"$text")"; then
    echo "WARN: possible Skill-tool-only content — reword the source skill, don't just edit the export:" >&2
    echo "$hits" >&2
  fi
}

usage() { echo "Usage: $0 [--all|<skill-dir>...] | --check <file>" >&2; exit 1; }

[[ $# -gt 0 ]] || usage

if [[ "$1" == --check ]]; then
  [[ $# -eq 2 ]] || usage
  file="$2"
  [[ -f "$file" ]] || { echo "no such file: $file" >&2; exit 1; }
  skill="$(sed -nE 's/^<!-- dev-pops-skills portable export: skill=([a-z0-9-]+).*/\1/p' "$file" | head -n1)"
  if [[ -z "$skill" || ! -d "$skills_root/$skill" ]]; then
    echo "FAIL: $file has no recognizable dev-pops-skills export header, or names an unknown skill ('$skill')" >&2
    exit 1
  fi
  fresh="$(render "$skills_root/$skill")"
  if diff -q <(printf '%s\n' "$fresh") "$file" >/dev/null; then
    echo "ok: $file matches a fresh export of $skill"
  else
    echo "STALE: $file no longer matches $skill. Regenerate with:" >&2
    echo "  $0 $skills_root/$skill" >&2
    diff <(printf '%s\n' "$fresh") "$file" >&2 || true
    exit 1
  fi
  exit 0
fi

if [[ "$1" == --all ]]; then
  set -- "$skills_root"/*/
fi

first=1
for d in "$@"; do
  [[ -d "$d" ]] || { echo "not a directory: $d" >&2; exit 1; }
  out="$(render "$d")"
  check_terms "$out"
  [[ $first -eq 1 ]] || printf '\n\n'
  first=0
  printf '%s\n' "$out"
done
